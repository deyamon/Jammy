import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

const responsive = await readFile(new URL('./responsive.css', import.meta.url), 'utf8')
const room = await readFile(new URL('./room.css', import.meta.url), 'utf8')
const base = await readFile(new URL('./styles.css', import.meta.url), 'utf8')
const app = await readFile(new URL('./App.jsx', import.meta.url), 'utf8')
const roomPage = await readFile(new URL('./pages/ListeningRoomPage.jsx', import.meta.url), 'utf8')
const lyricsProvider = await readFile(new URL('./services/lyricsProvider.js', import.meta.url), 'utf8')
const youtubeEmbed = await readFile(new URL('./playback/YoutubeEmbed.jsx', import.meta.url), 'utf8')

test('responsive rules cover desktop, tablet, compact mobile, and narrow mobile widths', () => {
  for (const width of [1180, 760, 520, 360]) assert.match(responsive, new RegExp(`@media\\s*\\(max-width:\\s*${width}px\\)`))
  assert.match(room, /@media\s*\(max-width:980px\)/)
  assert.match(room, /@media\s*\(max-width:680px\)/)
  assert.match(room, /\.room-layout\s*\{[^}]*grid-template-columns:[^}]*\}/s)
  assert.match(room, /\.room-mobile-tabs\s*\{[^}]*display:grid/s)
})

test('shared layout keeps mobile player accessible and panels switchable', () => {
  assert.match(responsive, /\.music-player\s*\{[^}]*safe-area-inset-bottom/s)
  assert.match(responsive, /\.expanded-player-grid\s*\{[^}]*grid-template-columns:[^}]*\}/s)
  assert.match(responsive, /\.expanded-panel\.expanded-panel-active\s*\{\s*display:block/s)
  assert.match(base, /\.youtube-player-viewport\s*\{[^}]*min-height:200px/s)
  assert.match(base, /\.youtube-player-dock\{position:relative/)
  assert.doesNotMatch(base, /\.youtube-player-dock\{position:fixed/)
  assert.match(responsive, /\.room-video-shell \.youtube-player-viewport\{[^}]*height:200px/s)
  assert.match(responsive, /\.room-view-panel\[hidden\]\{display:none\}/)
  assert.doesNotMatch(responsive, /mobile-persistent-youtube/)
  assert.match(roomPage, /role="tablist" aria-label="Player views"/)
  assert.match(roomPage, /playerView === 'video' && currentTrack\?\.provider === 'youtube' && activeRoomTab === 'player' \? <div className="room-video-shell">\{youtubePlayer\}/)
  assert.match(roomPage, /aria-live="polite" aria-busy=\{activeLyricsState\.status === 'loading'\}/)
  assert.match(roomPage, /Lyrics aren’t available for this track\./)
  assert.match(lyricsProvider, /result\.authorized === true/)
  assert.match(youtubeEmbed, /entry\.intersectionRatio > 0\.5/)
  assert.match(youtubeEmbed, /suspend: \(\) =>/)
  assert.match(app, /!roomSession && <MusicPlayer/)
  assert.match(app, /onSuspendYoutube=\{suspendRoomYoutube\}/)
  assert.match(app, /suspendRoomYoutube/)
  assert.match(roomPage, /if \(youtubeDetached\)[\s\S]*onPlaybackCommand\?\.\(\{ isPlaying: true/)
  assert.match(app, /onResumeYoutube=\{resumeRoomYoutube\}/)
  assert.match(app, /playbackController\.command\('applyRoomCommand', payload\)/)
  assert.match(youtubeEmbed, /applyRoomCommand: \(\{ isPlaying, positionMs \}\) =>/)
  assert.match(app, /<audio ref=\{audio\.audioRef\}/)
  assert.match(responsive, /\.room-dialog\s*\{[^}]*max-height:[^}]*100dvh/s)
  assert.match(responsive, /@media\(max-width:760px\)\{[^}]*\.spotify-result-row/s)
  assert.match(base, /\.spotify-embed-panel iframe\{[^}]*max-width:100%/)
})

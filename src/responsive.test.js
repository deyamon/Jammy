import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

const responsive = await readFile(new URL('./responsive.css', import.meta.url), 'utf8')
const room = await readFile(new URL('./room.css', import.meta.url), 'utf8')
const base = await readFile(new URL('./styles.css', import.meta.url), 'utf8')
const app = await readFile(new URL('./App.jsx', import.meta.url), 'utf8')
const roomPage = await readFile(new URL('./pages/ListeningRoomPage.jsx', import.meta.url), 'utf8')
const lyricsProvider = await readFile(new URL('./services/lyricsProvider.js', import.meta.url), 'utf8')
const youtubeEmbed = await readFile(new URL('./playback/YoutubeEmbed.jsx', import.meta.url), 'utf8')
const nowPlayingOverlay = await readFile(new URL('./components/NowPlayingOverlay.jsx', import.meta.url), 'utf8')

test('responsive rules cover desktop, tablet, compact mobile, and narrow mobile widths', () => {
  for (const width of [1180, 760, 520, 360]) assert.match(responsive, new RegExp(`@media\\s*\\(max-width:\\s*${width}px\\)`))
  assert.match(room, /@media\s*\(max-width:980px\)/)
  assert.match(room, /@media\s*\(max-width:680px\)/)
  assert.match(room, /\.room-layout\s*\{[^}]*grid-template-columns:[^}]*\}/s)
  assert.match(room, /\.room-mobile-tabs\s*\{[^}]*display:grid/s)
})

test('Home greets the authenticated account without hardcoded demo identity or date', () => {
  assert.match(app, /Welcome, \{account\.user\.username\}<span>\.<\/span>/)
  assert.doesNotMatch(app, /Good evening, Deyamon|Good evening, Jordan/)
  assert.doesNotMatch(app, /TUESDAY, OCTOBER 27/)
})

test('shared layout keeps mobile player accessible and panels switchable', () => {
  assert.match(responsive, /\.music-player\s*\{[^}]*safe-area-inset-bottom/s)
  assert.match(responsive, /\.expanded-player-grid\s*\{[^}]*grid-template-columns:[^}]*\}/s)
  assert.match(responsive, /\.expanded-panel\.expanded-panel-active\s*\{\s*display:block/s)
  assert.match(base, /\.youtube-player-viewport\s*\{[^}]*min-height:200px/s)
  assert.match(base, /\.youtube-player-dock\{position:relative/)
  assert.doesNotMatch(base, /\.youtube-player-dock\{position:fixed/)
  assert.match(responsive, /\.room-video-shell \.youtube-player-viewport\{[^}]*height:200px/s)
  assert.match(responsive, /\.room-view-panel\[hidden\]\{display:none\}/)
  assert.doesNotMatch(responsive, /mobile-persistent-youtube/)
  assert.match(roomPage, /role="tablist" aria-label="Player views"/)
  assert.match(roomPage, /getRoomProgressState\(currentTrack, \{ youtubeState, audioState: playerState \}\)/)
  assert.match(youtubeEmbed, /window\.setInterval\(\(\) => \{[\s\S]*getCurrentTime\?\.\(\)[\s\S]*}, 1000\)/)
  assert.match(youtubeEmbed, /if \(active\?\.getPlayerState\?\.\(\) === YT\.PlayerState\.PLAYING\) handlersRef/)
  assert.match(youtubeEmbed, /window\.clearInterval\(pollId\)/)
  assert.match(app, /nextPlayback\.currentTrackId !== roomPlaybackRef\.current\?\.currentTrackId\)\s*\{\s*setRoomYoutubeState\(\(previous\) => \(\{ \.\.\.previous, status: 'loading', currentTime: 0, duration: 0/)
  assert.match(roomPage, /currentTrack\?\.provider === 'youtube' \? <div className="room-video-shell">\{youtubePlayer\}/)
  assert.doesNotMatch(roomPage, /playerView === 'video' && currentTrack\?\.provider === 'youtube'/)
  const roomTabHandler = roomPage.match(/const changeRoomTab = \(tab\) => \{([^}]+)\}/)?.[1]
  assert.ok(roomTabHandler)
  assert.doesNotMatch(roomTabHandler, /onSuspendYoutube/)
  assert.match(roomPage, /aria-live="polite" aria-busy=\{activeLyricsState\.status === 'loading'\}/)
  assert.match(roomPage, /Lyrics aren’t available for this track\./)
  assert.match(lyricsProvider, /result\.authorized === true/)
  assert.match(youtubeEmbed, /entry\.intersectionRatio > 0\.5/)
  assert.match(youtubeEmbed, /suspend: \(\) =>/)
  assert.match(app, /!roomSession && account\.status === 'authenticated' && currentTrack && <MusicPlayer/)
  assert.match(app, /account\.status === 'authenticated' && <NowPlayingOverlay isOpen=\{nowPlayingOpen && !roomSession\}/)
  assert.doesNotMatch(app, /nowPlayingOpen && !roomSession && <NowPlayingOverlay/)
  assert.match(app, /ref=\{standaloneYoutubeRef\} track=\{standaloneTrack\}/)
  assert.match(app, /ref=\{roomYoutubeRef\} track=\{currentTrack\}/)
  assert.equal((app.match(/<YoutubeEmbed ref=\{standaloneYoutubeRef\}/g) ?? []).length, 1)
  assert.equal((app.match(/<YoutubeEmbed ref=\{roomYoutubeRef\}/g) ?? []).length, 1)
  assert.doesNotMatch(nowPlayingOverlay, /\shidden=\{!isOpen\}/)
  assert.match(nowPlayingOverlay, /aria-hidden=\{!isOpen\} inert=\{!isOpen\}/)
  assert.match(nowPlayingOverlay, /createPortal\([\s\S]*document\.body/)
  assert.match(nowPlayingOverlay, /getBoundingClientRect\(\)/)
  assert.match(nowPlayingOverlay, /addEventListener\('resize', updatePosition\)/)
  assert.match(nowPlayingOverlay, /addEventListener\('scroll', updatePosition, true\)/)
  assert.match(responsive, /\.keyboard-shortcuts-panel\{position:fixed;z-index:120/)
  assert.match(responsive, /overflow-y:auto;padding:16px/)
  const closeNowPlayingHandler = app.match(/const closeNowPlaying = \(\) => \{([^}]+)\}/)?.[1]
  assert.ok(closeNowPlayingHandler)
  assert.doesNotMatch(closeNowPlayingHandler, /pause|suspend|destroy/)
  const navigationHandler = app.match(/const navigate = \(page, tab\) => \{([^}]+)\}/)?.[1]
  assert.ok(navigationHandler)
  assert.doesNotMatch(navigationHandler, /pause|suspend|destroy/)
  assert.match(responsive, /\.expanded-player-backdrop-closed\{visibility:hidden;opacity:0;pointer-events:none\}/)
  assert.match(app, /setNowPlayingOpen\(false\)/)
  assert.match(app, /standaloneSnapshotRef\.current = createPlaybackSnapshot/)
  assert.match(app, /standaloneYoutubeRef\.current\?\.restorePlayback\?\.\(snapshot\)/)
  assert.match(app, /audio\.restorePlayback\(snapshot\)/)
  assert.match(app, /if \(!isCurrentRoomSession\(roomSessionRef\.current, sourceSession\)\) return/)
  assert.doesNotMatch(roomPage, /onSuspendYoutube|onResumeYoutube|youtubeDetached/)
  assert.doesNotMatch(app, /playbackController\.command\('applyRoomCommand', payload\)/)
  assert.match(app, /roomYoutubeRef\.current\?\.applyRoomCommand\?\.\(command\)/)
  assert.match(app, /expectedTrackId: playback\.currentTrackId/)
  assert.match(app, /expectedPlaybackToken: playback\.playbackToken/)
  assert.match(app, /roomYoutubeRef\.current\?\.applyRoomCommand\?\.\(authoritative\)/)
  assert.match(youtubeEmbed, /applyRoomCommand: \(\{ isPlaying, positionMs \}\) =>/)
  assert.match(app, /<audio ref=\{audio\.audioRef\}/)
  assert.match(responsive, /\.room-dialog\s*\{[^}]*max-height:[^}]*100dvh/s)
})
